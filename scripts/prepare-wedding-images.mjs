import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve('public/wedding');
const output = path.join(root, 'web');
await fs.mkdir(output, { recursive: true });
// Only use the originals directly inside wedding, never print copies in subfolders.
const files = (await fs.readdir(root, { withFileTypes: true }))
  .filter(file => file.isFile() && /\.jpe?g$/i.test(file.name))
  .map(file => file.name).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
if (!files.length) throw new Error('No JPG photos found in public/wedding');
const names = files.map(file => path.parse(file).name.toLowerCase());
if (new Set(names).size !== names.length) throw new Error('Duplicate wedding photo names');
const album = [];
const sizes = {};
for (const file of files) {
  const name = `${path.parse(file).name}.webp`;
  const info = await sharp(path.join(root, file)).rotate()
    .resize({ width: 1600, withoutEnlargement: true })
    .webp({ quality: 82 }).toFile(path.join(output, name));
  const { size } = await fs.stat(path.join(output, name));
  console.log(`${name}: ${Math.round(size / 1024)} KB`);
  const src = `/wedding/web/${name}`;
  album.push(src);
  sizes[src] = info.height / info.width;
}
await fs.mkdir(path.resolve('src/generated'), { recursive: true });
await fs.writeFile(path.resolve('src/generated/weddingAlbum.js'),
  `// Generated by npm run prepare-wedding-images.\nexport const weddingAlbum = ${JSON.stringify(album, null, 2)};\nexport const weddingImageRatios = ${JSON.stringify(sizes, null, 2)};\n`);
